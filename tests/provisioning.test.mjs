test("dual access requires both explicit entries; later completion never overwrites profiles",async()=>{
  const id=await create({version:1,orders:'operator',pos:'cashier'});const r=await rows(id);
  assert.equal(r.orders.length,1);assert.equal(r.pos.length,1);
  const single=await create({version:1,pos:'cashier'});const before=await rows(single);
  await query("update auth.users set raw_app_meta_data=$2 where id=$1",[single,JSON.stringify({nexo_memberships:{version:1,pos:'cashier',orders:'operator'}})]);
  assert.equal((await rows(single)).orders.length,0);
  await finalize(single);assert.deepEqual((await rows(single)).pos,before.pos);
  await query("update auth.users set raw_app_meta_data=$2 where id=$1",[legacy,JSON.stringify({nexo_memberships:{version:1,orders:'operator'}})]);
  await assert.rejects(finalize(legacy),/EXISTING_ORDERS_MEMBERSHIP_CONFLICT/);
  assert.deepEqual(await rows(legacy),legacyBefore);
});
test("completion rolls back both grants when an existing membership conflicts",async()=>{
  const id=await create({version:1,pos:'cashier'});
  await query("update pos_profiles set active=false where id=$1",[id]);
  await query("update auth.users set raw_app_meta_data=$2 where id=$1",[id,JSON.stringify({nexo_memberships:{version:1,orders:'operator',pos:'cashier'}})]);
  await assert.rejects(finalize(id),/EXISTING_POS_MEMBERSHIP_CONFLICT/);
  const r=await rows(id);assert.equal(r.orders.length,0);assert.equal(r.pos[0].active,false);
});
test("POS-only roles read catalog but cannot INSERT UPDATE DELETE or use Orders catalog RPC",async()=>{
  for(const role of ['cashier','admin']) {
    const id=await create({version:1,pos:role});
    for(const table of ['products','product_variants']) {
      assert.equal((await asRole('authenticated',id,`select * from public.${table}`)).length,1);
      await assert.rejects(asRole('authenticated',id,`insert into public.${table}(name,price,active) values('Bad',1,true)`),/row-level security/);
      assert.equal((await asRole('authenticated',id,`update public.${table} set price=999 returning id`)).length,0);
      assert.equal((await asRole('authenticated',id,`delete from public.${table} returning id`)).length,0);
    }
    await assert.rejects(asRole('authenticated',id,"select public.nexo_create_catalog_item('product',$1,null)",[JSON.stringify({name:'Bad',price:1,weight_kg:1})]),/Only active admins/);
  }
});
