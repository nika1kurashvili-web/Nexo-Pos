async function create(marker, userMetadata = {}, delayed = false) {
  const id=randomUUID();
  const app=marker === undefined ? {} : {nexo_memberships:marker};
  await query("insert into auth.users(id,email,raw_app_meta_data,raw_user_meta_data) values($1,'test@example.invalid',$2,$3)",
    [id,JSON.stringify(delayed ? {} : app),JSON.stringify(userMetadata)]);
  if (delayed) await query("update auth.users set raw_app_meta_data=$2 where id=$1",[id,JSON.stringify(app)]);
  return id;
}
async function asRole(role,id,sql,args=[]) {
  return db.transaction(async tx => {
    await tx.exec(`set local role ${role}`);
    await tx.query("select set_config('request.jwt.claim.sub',$1,true)",[id ?? ""]);
    return (await tx.query(sql,args)).rows;
  });
}
